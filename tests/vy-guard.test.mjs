/* vy-guard: обращение к пользователю только на «вы» (решение Алексея 05.10.2026: во всех
   приложениях RuStore - «вы», строчной, из уважения к тем, кто купил приложение).
   Сканирует ВСЁ, что видит человек: www/ (index.html, *.js, js/*.js без словарей BIP39), юрдоки,
   карточку стора, CHANGELOG (из него «Что нового»),
   «Данные для Консоли.txt» из набора публикации на Рабочем столе (если папка есть).
   Комментарии кода пропускаются - их пользователь не видит.
   Ловит: местоимения ты/твой/тебе..., глаголы 2-го лица ед.ч. (-ешь/-ишь), повелительные
   на «ты» по словарю, «Забыл/забыла» (прошедшее на «ты»; другие формы на -л
   не ловим: «SDK не добавил» - третье лицо, их проверяет чтение строк), «Вы/Ваш» с заглавной
   посреди фразы. \b в JS для кириллицы не работает - границы через lookbehind/lookahead.
   Мутация (05.10.2026): вставить «Сохрани копию» в строку www/js/app.js -> тест красный.
   Мутация (16.10.2026, 1.3.2): вернуть в Дизайн/src/card1.html «проверь сам» -> красный. */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const DESK_SET = path.join(ROOT, '..', '..', '..', 'Сейф-RuStore-публикация', 'Данные для Консоли.txt');

const W = '(?<![а-яёА-ЯЁ])', E = '(?![а-яёА-ЯЁ])';
const PRON = 'ты|тебя|тебе|тобой|твой|твоя|твоё|твое|твои|твоих|твоим|твоей|твоему|твою|твоими|твоего';
const IMP = 'нажми|добавь|выбери|сохрани|открой|закрой|отметь|запиши|введи|войди|посмотри|начни|удали|придумай|повтори|приложи|подтверди|попробуй|разреши|включи|выключи|отключи|проверь|вставь|скопируй|активируй|смени|измени|впиши|напиши|пиши|держи|обнови|освободи|восстанови|верни|листай|полистай|зафиксируй|допиши|поправь|исправь|отмечай|вернись|сделай|делай|смотри|перенеси|забудь|помни|запомни|вспомни|оставь|переустанови|установи|сотри|очисти|поставь|запланируй|наметь|жми|тапни|щёлкни|кликни|задай|укажи|заполни|найди|покажи|создай|купи|оплати|скачай|загрузи|выгрузи|перейди|зайди|подожди|жди|учти|прочитай|прочти|звони|позвони|обратись|сверься|присмотрись|продолжи|отправь|поделись';
const PAST = 'забыл|забыла|запомнил|запомнила';
const TY_RE = new RegExp(W + '(?:' + PRON + '|' + IMP + '|' + PAST + ')' + E + '|' + W + '[а-яё]{2,}(?:ешь|ёшь|ишь|ешься|ёшься|ишься)' + E, 'giu');
const CAP_VY = /[а-яё,;:)»] (?:Вы|Вас|Вам|Вами|Ваш|Ваша|Ваше|Ваши|Вашего|Вашей|Вашим|Ваших|Вашу|Вашими)(?![а-яё])/g;
/* Белый список - слова, которые совпадают с шаблоном, но не обращение на «ты». */
const OK = new Set([
  'лишь', // наречие, не глагол на -ишь
  'тишь', 'мышь', 'глушь', 'вишь',
]);

function visible(src) {
  return src.replace(/<!--[\s\S]*?-->/g, ' ').replace(/<style[\s\S]*?<\/style>/g, ' ')
    .replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:'"\\])\/\/[^\n]*/g, '$1');
}
function tyHits(text) { return [...new Set((text.match(TY_RE) || []).filter((w) => !OK.has(w.toLowerCase())))]; }
function capHits(text) { return text.match(CAP_VY) || []; }

const SKIP = new Set(['capacitor.js', 'bip39-wordlist.js', 'wordlist.js']); // сторонний мост и словари слов
const FILES = [
  ...fs.readdirSync(path.join(ROOT, 'www')).filter((f) => /\.(js|html)$/.test(f) && !SKIP.has(f)).map((f) => 'www/' + f),
  ...fs.readdirSync(path.join(ROOT, 'www', 'js')).filter((f) => /\.js$/.test(f) && !SKIP.has(f)).map((f) => 'www/js/' + f),
  'legal/privacy.html', 'legal/terms.html', 'store/card-rustore.txt', 'CHANGELOG.md',
  /* Скриншоты витрины RuStore (исходники картинок): 1.3.2 - «проверь сам», «знаешь только ты» на
     скриншоте 1 прошли мимо заслона, потому что картинки не сканировались. card1-staryy - архив. */
  // публичный репозиторий: исходников скриншотов витрины (Дизайн/) нет - тогда их проверка пропускается
  ...(fs.existsSync(path.join(ROOT, 'Дизайн', 'src')) ? fs.readdirSync(path.join(ROOT, 'Дизайн', 'src')).filter((f) => /^card\d+\.html$/.test(f)).map((f) => 'Дизайн/src/' + f) : []),
];
const INTERNAL = (f) => !fs.existsSync(path.join(ROOT, f)) && 'внутренний файл не входит в публичный репозиторий';

test('vy-guard: самопроверка - ловит «ты», пропускает «вы»', () => {
  assert.deepEqual(tyHits('Сохрани копию. Твои записи. Забыл код? Хочешь - нажми.'), ['Сохрани', 'Твои', 'Забыл', 'Хочешь', 'нажми']);
  assert.deepEqual(tyHits('Сохраните копию. Ваши записи. Забыли код? Лишь бы тишь.'), []);
  assert.equal(capHits('Если Вы забыли, Ваши данные').length, 2);
  assert.equal(capHits('Вы забыли. Ваши данные целы.').length, 0);
});

for (const f of FILES) {
  test('vy-guard: ' + f + ' - только «вы»', { skip: INTERNAL(f) }, () => {
    const s = visible(fs.readFileSync(path.join(ROOT, f), 'utf8'));
    assert.deepEqual(tyHits(s), [], f + ': обращение на «ты»');
    assert.deepEqual(capHits(s), [], f + ': «вы» посреди фразы - строчной');
  });
}

test('vy-guard: «Данные для Консоли.txt» в наборе публикации (если папка есть на этой машине)', (t) => {
  if (!fs.existsSync(DESK_SET)) return t.skip('нет папки публикации на Рабочем столе');
  const s = fs.readFileSync(DESK_SET, 'utf8');
  assert.deepEqual(tyHits(s), []);
  assert.deepEqual(capHits(s), []);
});
