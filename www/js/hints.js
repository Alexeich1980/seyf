const FALLBACK = 'Раздел «Сейфа». Подсказка появится в следующем обновлении.';

// Массив абзацев подсказки (для рендера отдельными <p>). Неизвестный раздел → фолбэк.
export function getHintParagraphs(section) {
  const h = HINTS[section];
  if (Array.isArray(h) && h.length) return h.slice();
  if (typeof h === 'string' && h.trim()) return [h];
  return [FALLBACK];
}

// Склеенный текст подсказки (совместимость: раньше подсказка была одной строкой).
export function getHint(section) {
  return getHintParagraphs(section).join('\n\n');
}
