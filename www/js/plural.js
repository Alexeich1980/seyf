// plural.js - русское склонение существительных по числу (mobile-only, не core).
// one - 1 (яблоко), few - 2..4 (яблока), many - 0/5..20 (яблок). Учитывает 11..14.
// Вынесено из app.js в один модуль, чтобы правило проверялось тестом (счётчики страниц,
// лимиты paywall, чипы длины seed-фразы), а не дублировалось.
export function plural(n, one, few, many) {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return few;
  return many;
}
