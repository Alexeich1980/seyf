// share.js — сборка текста «Копировать все реквизиты» (п.21, mobile-only, чистая логика).
// Форматирует реквизиты «подпись: значение» через пустую строку, чтобы вставить в чат/письмо. Подписи
// берём ИЗ СХЕМЫ раздела (sectionsx.EXTRA_SCHEMA.requisites) — так «Расчётный счёт», «ОГРН/
// ОГРНИП» и любые будущие поля подтягиваются автоматически, без второго списка, который бы
// разошёлся (заслон против рассинхрона подписей, п.7/п.8). Заголовок «Название» (первое поле)
// и «Заметку» (textarea) НЕ включаем: «Название» — ярлык карточки (Бизнес/Жена), заметка —
// личная пометка. Пустые поля пропускаются. Копирование в буфер делает app.js. На функцию — тест.
import { EXTRA_SCHEMA } from './sectionsx.js';

export function buildRequisitesShareText(entry, schema = EXTRA_SCHEMA.requisites) {
  const e = entry || {};
  const lines = [];
  for (const f of schema || []) {
    if (f.key === 'name' || f.type === 'textarea') continue;   // ярлык и заметка не в реквизитах
    const v = String(e[f.key] == null ? '' : e[f.key]).trim();
    if (v) lines.push(f.label + ': ' + v);
  }
  // C10 (1.2.23): заполненные произвольные поля - тоже реквизиты («подпись: значение»). Раньше
  // «Копировать все» их молча пропускал (напр. «Назначение платежа», «Код филиала»).
  for (const cf of e.customFields || []) {
    const v = String(cf && cf.value != null ? cf.value : '').trim();
    if (!v) continue;
    const name = String(cf.name == null ? '' : cf.name).trim() || 'Поле';
    lines.push(name + ': ' + v);
  }
  // 1.2.20: пункты разделены ПУСТОЙ строкой - после вставки в чат/заметку реквизиты читаются
  // блоками, а не сплошным текстом (живой тест Алексея).
  return lines.join('\n\n');
}
