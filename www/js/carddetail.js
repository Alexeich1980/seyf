// carddetail.js — чистая логика «разворота карточки на месте» (заход 2 п.6, mobile-only).
// Тап по карточке НЕ-документа разворачивает её (секреты + действия), повторный — сворачивает.
// Полноэкранный просмотр остаётся ТОЛЬКО для Документов со сканами. Без DOM — на функциях тест.

// Режим открытия карточки по тапу: теперь ВСЕГДА 'expand' - разворот на месте (п.11). Документы
// со сканами больше не открывают полноэкранный просмотр сразу по тапу: сначала разворот (мета +
// миниатюры), а полноэкранный скан - явным действием (тап по миниатюре или «Открыть сканы» внутри
// развёрнутой карточки). Функция сохранена для совместимости и теста.
export function cardOpenMode(_section, _entry) {
  return 'expand';
}

// Следующее состояние разворота (идемпотентная чистая функция — для теста и вызова из DOM).
export function nextExpanded(isExpanded) { return !isExpanded; }

// Какие действия показать в развороте карточки. edit/delete — всегда; share (Копировать все
// реквизиты) — у Реквизитов. Кнопки «Открыть сканы» больше нет (D2): скан открывается тапом по
// любой миниатюре. Контактные «Позвонить»/«Открыть» рисует decorateContactCard — здесь не дублируем.
export function expandActions(section, _entry) {
  return {
    edit: true,
    del: true,
    share: section === 'requisites',
    open: false,
  };
}
